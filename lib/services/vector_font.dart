/// Jeden znak [VectorFont]u.
class VectorGlyph {
  /// Šírka znaku (aj s optickým okrajom) v jednotkách fontu.
  final double width;

  /// Čiary znaku – každá je plochý zoznam `x0, y0, x1, y1, …`.
  final List<Float64List> paths;

  const VectorGlyph(this.width, this.paths);
}

/// Rozparsuje kompaktný zápis `"x,y x,y …"` na ploché súradnice.
Float64List _p(String coords) {
  final numbers = <double>[];
  for (final pair in coords.split(' ')) {
    if (pair.isEmpty) continue;
    final comma = pair.indexOf(',');
    numbers
      ..add(double.parse(pair.substring(0, comma)))
      ..add(double.parse(pair.substring(comma + 1)));
  }
  return Float64List.fromList(numbers);
}

/// Oblúk (alebo celá elipsa) ako lomená čiara – pero nevie kresliť krivky.
Float64List _arc(
  double cx,
  double cy,
  double rx,
  double ry,
  double startDegrees,
  double sweepDegrees, {
  int segments = 12,
}) {
  final out = Float64List((segments + 1) * 2);
  final start = startDegrees * math.pi / 180.0;
  final sweep = sweepDegrees * math.pi / 180.0;
  for (var i = 0; i <= segments; i++) {
    final angle = start + sweep * i / segments;
    out[i * 2] = cx + rx * math.cos(angle);
    out[i * 2 + 1] = cy + ry * math.sin(angle);
  }
  return out;
}

